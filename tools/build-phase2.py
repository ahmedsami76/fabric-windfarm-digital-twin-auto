    single = {"visualType": kind,
              "projections": {role: [{"queryRef": f"{f['table']}.{f['name']}"} for f in group]
                              for role, group in roles.items()},
              "prototypeQuery": {"Version": 2, "From": [{"Name": a, "Entity": t, "Type": 0} for t, a in alias.items()],
                                 "Select": select},
              "drillFilterOtherVisuals": True}
    if title:
        single["vcObjects"] = {"title": [{"properties": {
            "show": {"expr": {"Literal": {"Value": "true"}}},
            "text": {"expr": {"Literal": {"Value": "'" + title.replace("'", "''") + "'"}}}}}]}
    position = {"x": x, "y": y, "z": 0, "width": w, "height": h}
    config = {"name": uuid.uuid4().hex[:20], "layouts": [{"id": 0, "position": position}], "singleVisual": single}
    return {**position, "config": json.dumps(config), "filters": "[]"}


