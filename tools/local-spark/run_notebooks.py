#!/usr/bin/env python3
"""Run the Fabric notebooks in a local Spark session, without Fabric.

    pip install pyspark pandas numpy pyarrow tabulate        # and a Java runtime that fits the Spark version
    python3 tools/local-spark/run_notebooks.py                           # run notebooks 01 to 04
    python3 tools/local-spark/run_notebooks.py --answers docs/question-bank-example-answers.md

It executes every code cell of the four notebooks, in order, against a scratch folder that
stands in for the Lakehouse. This shows that the Python, the Spark calls and the SQL of the
notebooks work. Two things differ from Fabric, because the Delta Lake library is not part of
a plain Spark installation:

  * tables are written as Parquet instead of Delta,
  * the one DELETE statement of notebook 03 is replaced by an equivalent rewrite of the table.

Used before delivery with Spark 3.5 on Python 3.11 (as in Fabric Runtime 1.3) and with
Spark 4.1 on Python 3.13 (as in Fabric Runtime 2.0).
"""
from __future__ import annotations

import argparse
import json
import os
import shutil
import sys
import tempfile
import time
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
NOTEBOOKS = ["01_load_reference_data", "02_generate_history", "03_refresh_forecast", "04_question_bank"]
EMULATED_DELETE = '''_keep = spark.table(TABLE).where("ForecastType <> 'Latest'").toPandas()
spark.sql(f"DROP TABLE {TABLE}")
spark.createDataFrame(_keep).write.format("parquet").saveAsTable(TABLE)'''


def session(lakehouse: Path):
    from pyspark.sql import SparkSession
    os.environ.setdefault("PYSPARK_PYTHON", sys.executable)
    os.environ.setdefault("PYSPARK_DRIVER_PYTHON", sys.executable)
    spark = (SparkSession.builder.master("local[2]").appName("windfarm-notebooks")
             .config("spark.driver.memory", "4g").config("spark.ui.enabled", "false")
             .config("spark.sql.warehouse.dir", str(lakehouse / "Tables"))
             .config("spark.sql.shuffle.partitions", "4")
             .config("spark.driver.extraJavaOptions", f"-Dderby.system.home={lakehouse / 'derby'}")
             .enableHiveSupport().getOrCreate())
    spark.sparkContext.setLogLevel("ERROR")
    return spark


def run_notebooks(spark, lakehouse: Path, only: list[str]) -> int:
    namespace = {"spark": spark, "display": lambda df: df.show(30, truncate=60)}
    cells = 0
    for name in NOTEBOOKS:
        if only and name[:2] not in only:
            continue
        notebook = json.loads((REPO / "fabric" / "notebooks" / f"{name}.ipynb").read_text(encoding="utf-8"))
        print(f"\n=================== {name}", flush=True)
        for number, cell in enumerate(notebook["cells"]):
            if cell["cell_type"] != "code":
                continue
            source = "".join(cell["source"])
            source = source.replace("/lakehouse/default", str(lakehouse))
            source = source.replace('.format("delta")', '.format("parquet")').replace('.option("overwriteSchema", "true")', "")
            source = source.replace('''spark.sql(f"DELETE FROM {TABLE} WHERE ForecastType = 'Latest'")''', EMULATED_DELETE)
            started = time.time()
            exec(compile(source, f"{name}[{number}]", "exec"), namespace)
            cells += 1
            print(f"--- cell {number} ok in {time.time() - started:.1f}s", flush=True)
    return cells


def write_answers(spark, out: Path) -> int:
    import pandas as pd
    sys.path.insert(0, str(REPO / "tools"))
    import question_bank as qb

    def tidy(pdf):
        shown = pdf.copy()
        for c in shown.columns:
            col = shown[c]
            if pd.api.types.is_bool_dtype(col):
                shown[c] = col.map(lambda v: "yes" if v else "no")
            elif pd.api.types.is_float_dtype(col):
                values = col.dropna()
                if len(values) and (values == values.round(0)).all():
                    shown[c] = col.map(lambda v: "" if pd.isna(v) else f"{int(v):,}" if abs(v) >= 10000 else f"{int(v)}")
                else:
                    shown[c] = col.map(lambda v: "" if pd.isna(v) else f"{v:,.4f}".rstrip("0").rstrip("."))
            elif pd.api.types.is_integer_dtype(col):
                shown[c] = col.map(lambda v: f"{v:,}" if abs(v) >= 10000 else f"{v}")
            else:
                shown[c] = col.map(lambda v: "" if v is None or (isinstance(v, float) and pd.isna(v)) else
                                   (str(v)[:150] + " …" if len(str(v)) > 150 else str(v)).replace("|", "/"))
        return shown

    spark.conf.set("spark.sql.session.timeZone", "UTC")
    spark.sql(qb.SETUP_SQL)
    as_of = spark.sql("SELECT date_format(AsOf, 'yyyy-MM-dd HH:mm') FROM q_asof").first()[0]
    lines = ["# Question bank: example answers", "",
             f"Generated by running the {len(qb.QUESTIONS)} reference queries of notebook `04_question_bank` against a history "
             f"that ends at **{as_of} UTC**. The run was made in a local Spark {spark.version} session with "
             "`tools/local-spark/run_notebooks.py`, not in Fabric; see \"What has and has not been verified\" in "
             "[00-architecture.md](00-architecture.md).", "",
             "Use it to see what the answers look like before you run the notebook, and to check the pattern of your own "
             "results: the same turbines at the top and bottom, numbers of the same size. Your numbers will differ a "
             "little, because the planted stories are placed relative to the day your history ends. Long texts are cut "
             "after 150 characters here.", "",
             "The questions, by role, are in [05-question-bank.md](05-question-bank.md); the definitions of the measures "
             "are in [04-use-cases-and-data-audit.md](04-use-cases-and-data-audit.md).", ""]
    failed = 0
    for key, (title, _) in qb.PERSONAS.items():
        own = [q for q in qb.QUESTIONS if q["id"].startswith(key)]
        if not own:
            continue
        lines += [f"## {title}", ""]
        for q in own:
            lines += [f"### {q['id']}  {q['question']}", ""]
            if q.get("note"):
                lines += [q["note"], ""]
            try:
                lines += [tidy(spark.sql(q["sql"]).toPandas()).to_markdown(index=False, disable_numparse=True), ""]
            except Exception as exc:                      # noqa: BLE001 - report and go on
                failed += 1
                lines += [f"FAILED: {str(exc)[:800]}", ""]
                print(f"{q['id']} FAILED: {str(exc)[:300]}", flush=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"\nwrote {out} ({len(qb.QUESTIONS) - failed} answers, {failed} failed)")
    return failed


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--only", nargs="*", default=[], metavar="NN", help="notebook numbers to run, for example 02 04")
    parser.add_argument("--answers", metavar="FILE", help="also run the question bank and write its answers as markdown")
    parser.add_argument("--lakehouse", metavar="DIR", help="scratch folder that stands in for the Lakehouse (default: a temporary one)")
    args = parser.parse_args()

    lakehouse = Path(args.lakehouse).resolve() if args.lakehouse else Path(tempfile.mkdtemp(prefix="windfarm-lakehouse-"))
    files = lakehouse / "Files"
    if not args.only or "01" in args.only:
        shutil.rmtree(lakehouse, ignore_errors=True)
        files.mkdir(parents=True)
        shutil.copytree(REPO / "data" / "reference", files / "reference")
        shutil.copytree(REPO / "data" / "sop", files / "sop")
    os.chdir(lakehouse)                                   # notebook 01 reads "Files/reference" relative to the Lakehouse
    spark = session(lakehouse)
    print(f"Spark {spark.version}, Python {sys.version.split()[0]}, ANSI mode {spark.conf.get('spark.sql.ansi.enabled')}, "
          f"Lakehouse stand-in: {lakehouse}")
    cells = run_notebooks(spark, lakehouse, args.only)
    print(f"\n{cells} code cells ran without error")
    failed = write_answers(spark, Path(args.answers).resolve()) if args.answers else 0
    spark.stop()
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
