def live_kql() -> str:
    out = ["// " + "=" * 76,
           "// 92-question-bank-live.kql : the questions of the question bank that are answered",
           "// from live data. Generated by tools/build-notebooks.py from tools/question_bank.py.",
           "// Run one query at a time in a KQL queryset connected to the KQL database windfarm.",
           "// The other questions run against the Lakehouse: notebook 04_question_bank.",
           "// " + "=" * 76, ""]
    for q in qb.LIVE_QUESTIONS:
        out.append(f"// {q['id']}  {q['question']}")
        if q.get("note"):
            out.append(f"// {q['note']}")
        out.append(q["kql"].strip())
        out.append("")
    return "\n".join(out)


