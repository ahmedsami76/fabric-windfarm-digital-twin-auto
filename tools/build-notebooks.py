def library_source() -> str:
    """The three modules as one cell: package-relative imports and the command line part removed."""
    parts = ["# Generated by tools/build-notebooks.py from simulator/windfarm_sim/{catalog,climate,history}.py.\n"
             "# Do not edit here: change the modules and run the tool again.\n"
             "from __future__ import annotations\n"]
    for name in MODULES:
        text = (PACKAGE / f"{name}.py").read_text(encoding="utf-8")
        if CUT in text:
            text = text[:text.index(CUT)]
        text = text.replace("from __future__ import annotations\n", "")
        text = re.sub(r"^from \.\w+ import \([^)]*\)\n", "", text, flags=re.MULTILINE)
        text = re.sub(r"^from \.\w+ import .*\n", "", text, flags=re.MULTILINE)
        parts.append(f"\n# {'=' * 30} {name}.py {'=' * 30}\n{text.rstrip()}\n")
    return "".join(parts)


