def to_spark(pdf):
    """pandas to Spark. Missing numbers, dates and empty text all become NULL, so that
    averages, counts and joins behave as a SQL user or an agent expects. Single-precision
    numbers become double precision, rounded, so that 3.2 reads as 3.2 everywhere. Days
    stored as text become dates."""
    df = spark.createDataFrame(pdf)
    for field in df.schema.fields:
        column = F.col(field.name)
        if isinstance(field.dataType, FloatType):
            df = df.withColumn(field.name, F.when(F.isnan(column), None)
                               .otherwise(F.round(column.cast("double"), 4)))
        elif isinstance(field.dataType, DoubleType):
            df = df.withColumn(field.name, F.when(F.isnan(column), None).otherwise(column))
        elif isinstance(field.dataType, StringType) and field.name.endswith("Date"):
            df = df.withColumn(field.name, F.to_date(column))
        elif isinstance(field.dataType, StringType):
            df = df.withColumn(field.name, F.when(column == "", None).otherwise(column))
    return df


