"""Phase 5b: what the operations agent needs to propose a curtailment, to say what it costs, and to act.

tools/build-phase5.py writes three files from this module:
    fabric/kql/06-remediation-readiness.kql
    fabric/operations-agent/phase5b-agent-setup.txt
    fabric/operations-agent/phase5b-action.txt
tools/operations_agent.py gives the same instructions and the same action to the agent through the Fabric API.

Every figure comes from data/reference, read here, so that the agent's message, the KQL and the guide
cannot say different things. The thresholds are those of the Phase 3 agent (tools/agent_spec.py).
"""
from __future__ import annotations

import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REFERENCE = ROOT / "data" / "reference"

TABLE = "GearboxDecisionLive"
AGENT = "WindFarmGearboxWatch"
ACTION_NAME = "Curtail turbine"
NOTEBOOK = "12_send_edge_command"
REQUESTED_BY = f"operations agent {AGENT}, approved in Teams"
CURTAIL_PERCENT = 30            # the limit the turbine controller itself applies at 8 mm/s (GBX-VIB-CRIT)
CURTAIL_DURATION = "60m"
EARLY_VIBRATION = 4.0           # mm/s, as in Phase 3
ALARM_VIBRATION = 5.5           # mm/s, the controller's GBX-VIB-HIGH
EARLY_OIL_TEMP = 72.0           # degC, as in Phase 3
ALARM_OIL_TEMP = 78.0           # degC, the controller's GBX-OIL-TEMP-HIGH


def _rows(name: str) -> list[dict]:
    with open(REFERENCE / name, newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def facts() -> dict:
    """The figures of the decision, each from the reference file that owns it."""
    rated = {float(row["ratedPowerKw"]) for row in _rows("turbines.csv")}
    warranty = {row["warrantyEndDate"] for row in _rows("components.csv") if row["componentCode"] == "GBX"}
    if len(rated) != 1 or len(warranty) != 1:
        raise SystemExit("The turbines no longer share one rated power or one warranty date: the table needs them per turbine.")
    ppa = next(row for row in _rows("contracts.csv") if row["contractId"] == "CT-PPA-001")
    unit = next(row for row in _rows("spare_parts.csv") if row["partId"] == "SP-GBX-UNIT")
    rated_kw = rated.pop()
    return {
        "ratedPowerKw": rated_kw,
        "limitKw": rated_kw * CURTAIL_PERCENT / 100.0,
        "priceUsdPerMwh": float(ppa["priceUsdPerMwh"]),
        "exchangeUsd": int(float(unit["unitCostUsd"])),
        "leadTimeDays": int(unit["leadTimeDays"]),
        "warrantyEnd": warranty.pop(),
    }


def cost_per_hour(active_power_kw: float, f: dict | None = None) -> float:
    """What the KQL computes, in Python, for the tests and the guide's examples."""
    f = f or facts()
    lost_kw = max(0.0, active_power_kw - f["limitKw"])
    return round(lost_kw / 1000.0 * f["priceUsdPerMwh"], 0)


COLUMNS = [
    ("Timestamp", "datetime", "Time of the newest measurement in the batch, UTC"),
    ("TurbineId", "string", "Turbine, WT-01 to WT-12. Identifies the monitored object"),
    ("GearboxVibration", "real", "Gearbox vibration, mm/s, average of the batch. Early warning at 4, controller alarm at 5.5"),
    ("GearboxOilTemp", "real", "Gearbox oil temperature, degrees Celsius, average of the batch. Early warning at 72, controller alarm at 78"),
    ("GearboxBearingTemp", "real", "Gearbox bearing temperature, degrees Celsius, average of the batch"),
    ("ActivePower", "real", "Power the turbine delivers now, kW, average of the batch"),
    ("WindSpeed", "real", "Wind speed at the nacelle, m/s, average of the batch"),
    ("CurtailToPercent", "int", "The power limit the action 'Curtail turbine' should set, percent of rated power"),
    ("PowerAfterCurtailKw", "real", "Power the turbine would deliver under that limit at the current wind, kW"),
    ("CurtailCostPerHourUsd", "real", "Revenue lost per hour by curtailing now, USD: the power above the limit at the contract price. 0 when the turbine already runs below the limit"),
    ("CurtailCostPerDayUsd", "real", "The same per day if the wind stayed as it is, USD"),
    ("GearboxExchangeUsd", "long", "Price of a gearbox exchange unit, USD: what is at stake if the gearbox fails"),
    ("GearboxLeadTimeDays", "int", "Days until a gearbox exchange unit arrives"),
    ("WarrantyDaysLeft", "int", "Days until the drivetrain warranty ends. 0 or less: it has ended, and the owner pays for a failure"),
]


def kql() -> str:
    f = facts()
    schema = ", ".join(f"{name}: {kind}" for name, kind, _ in COLUMNS)
    docs = ",\n".join(f'    {name}: "{text}"' for name, _, text in COLUMNS)
    names = ", ".join(name for name, _, _ in COLUMNS)
    return f"""// Phase 5b: what the operations agent needs to propose a curtailment and to say what it costs.
// Generated by tools/build-phase5.py from tools/remediation_spec.py and data/reference. Change it there.
//
// Run the blocks one at a time in a query window on the KQL database WindFarmEH.
//
// The operations agent reads tables, not functions, and a rule speaks of the columns of the table it
// watches. So the figures a decision needs are written next to the gearbox readings as the telemetry
// arrives: one row per running turbine for each batch, about every 20 seconds.
//
//   The action limits a turbine to {CURTAIL_PERCENT} percent of its rated {f['ratedPowerKw']:.0f} kW, which is {f['limitKw']:.0f} kW.
//   The power above that limit is lost, at the contract price of {f['priceUsdPerMwh']} USD/MWh (contracts.csv, CT-PPA-001).
//   A gearbox exchange unit costs {f['exchangeUsd']} USD and arrives after {f['leadTimeDays']} days (spare_parts.csv, SP-GBX-UNIT).
//   The drivetrain warranty ends on {f['warrantyEnd']} (components.csv, all twelve gearboxes).
//
// Readings are averaged over the batch, as in GearboxVsFleetLive, so that one noisy reading is no crossing.
// Only running and derated turbines get a row: a curtailed or stopped turbine is not watched while it is so.

// Block 1. The table, its descriptions for the agent, and the update policy that fills it.
.execute database script <|
.create-merge table {TABLE} ({schema})
//
.alter table {TABLE} docstring 'One row per running turbine for each batch of telemetry: its gearbox readings, and the cost of limiting it to {CURTAIL_PERCENT} percent of rated power against what a gearbox failure would cost. Made for the operations agent of Phase 5b.'
//
.alter-merge table {TABLE} column-docstrings (
{docs}
)
//
.alter table {TABLE} policy ingestiontime true
//
.alter-merge table {TABLE} policy retention softdelete = 30d
//
.create-or-alter function with (folder = 'Ingestion', docstring = 'Update policy: gearbox readings of each running turbine with the cost of curtailing it') Expand_{TABLE}() {{
    let RatedPowerKw = {f['ratedPowerKw']};
    let CurtailPercent = {CURTAIL_PERCENT};
    let PriceUsdPerMwh = {f['priceUsdPerMwh']};
    let ExchangeUsd = long({f['exchangeUsd']});
    let LeadTimeDays = {f['leadTimeDays']};
    let WarrantyEnd = datetime({f['warrantyEnd']});
    TurbineTelemetry
    | where State in ('RUNNING', 'DERATED')
    | summarize Timestamp = max(Timestamp),
                GearboxVibration = round(avg(GearboxVibration), 2), GearboxOilTemp = round(avg(GearboxOilTemp), 1),
                GearboxBearingTemp = round(avg(GearboxBearingTemp), 1), ActivePower = round(avg(ActivePower), 0),
                WindSpeed = round(avg(WindSpeed), 1) by TurbineId
    | extend CurtailToPercent = toint(CurtailPercent),
             PowerAfterCurtailKw = round(min_of(ActivePower, RatedPowerKw * CurtailPercent / 100.0), 0)
    | extend CurtailCostPerHourUsd = round((ActivePower - PowerAfterCurtailKw) / 1000.0 * PriceUsdPerMwh, 0)
    | extend CurtailCostPerDayUsd = CurtailCostPerHourUsd * 24,
             GearboxExchangeUsd = ExchangeUsd, GearboxLeadTimeDays = toint(LeadTimeDays),
             WarrantyDaysLeft = toint(datetime_diff('day', WarrantyEnd, Timestamp))
    | project {names}
}}
//
.alter table {TABLE} policy update @'[{{"IsEnabled": true, "Source": "TurbineTelemetry", "Query": "Expand_{TABLE}()", "IsTransactional": false, "PropagateIngestionProperties": false}}]'

// Block 2. Check, a minute later: the newest row of each running turbine. At a wind that gives more
// than {f['limitKw']:.0f} kW, CurtailCostPerHourUsd is above 0; below that it is 0, and curtailing would change nothing.
{TABLE}
| where Timestamp > ago(5m)
| summarize arg_max(Timestamp, GearboxVibration, GearboxOilTemp, ActivePower, PowerAfterCurtailKw, CurtailCostPerHourUsd, CurtailCostPerDayUsd, WarrantyDaysLeft) by TurbineId
| order by TurbineId asc

// Block 3. What the agent's rule 1 looks at, for one turbine: the batches of the last 15 minutes.
// A crossing is a row above {EARLY_VIBRATION:g} mm/s after a row at or below it.
{TABLE}
| where Timestamp > ago(15m) and TurbineId == 'WT-03'
| project Timestamp, GearboxVibration, GearboxOilTemp, ActivePower, CurtailCostPerHourUsd
| order by Timestamp desc

// To remove Phase 5b from the database:
// .drop table {TABLE} ifexists
// .drop function Expand_{TABLE} ifexists
"""


def goals() -> str:
    f = facts()
    return (f"Protect the gearboxes of the Northwind Ridge wind farm. A gearbox exchange costs about {f['exchangeUsd']:,} USD and months of lost\n"
            "production; a bearing replaced in time costs a fraction of that. Find a gearbox that starts to run rough or hot\n"
            "before the turbine controller has to derate or stop the turbine, tell the on-call engineer which turbine it is\n"
            "and what the numbers are, and propose to limit the power of that turbine until it has been inspected, with what\n"
            "that costs. The engineer decides. Do not raise the same condition again while it lasts.")


def instructions() -> str:
    return f"""*** Operational Instructions ***
1. Alert me when the gearbox vibration of a turbine crosses above {EARLY_VIBRATION:g} mm/s. This is an early warning: the turbine controller only alarms at {ALARM_VIBRATION:g} mm/s. Recommend the action '{ACTION_NAME}' for that turbine.

*** Semantic Instructions ***
1. Information about a turbine can be found in the '{TABLE}' table. Each turbine is identified by the 'TurbineId' column (WT-01 to WT-12). The table only holds turbines that are running.
2. 'Timestamp' is the time of the measurement in UTC. There is one row per turbine about every 20 seconds.
3. Gearbox vibration is the column 'GearboxVibration' in mm/s. Gearbox oil temperature is 'GearboxOilTemp' and gearbox bearing temperature is 'GearboxBearingTemp', both in degrees Celsius; the controller alarms at an oil temperature of {ALARM_OIL_TEMP:g} degrees. 'ActivePower' is the power of the turbine in kW.
4. 'CurtailCostPerHourUsd' is the revenue lost per hour, in USD, if the turbine is limited now, and 'CurtailCostPerDayUsd' the same per day. 'GearboxExchangeUsd' is the price of a gearbox exchange in USD, 'GearboxLeadTimeDays' the days until one arrives, and 'WarrantyDaysLeft' the days until the drivetrain warranty ends; when it is 0 or less the warranty has ended and the owner pays for a failure.
5. Begin the message with the cost of acting and of not acting, taken from the latest row of the turbine: what limiting it costs per hour and per day, what a gearbox exchange costs and how long it takes to arrive, and how many days of warranty are left, or that the warranty has ended. Then name the turbine and give its latest gearbox vibration, gearbox oil temperature, gearbox bearing temperature and power.
6. When you recommend the action '{ACTION_NAME}', use the 'TurbineId' of the turbine as 'turbine', the value of 'CurtailToPercent' as 'percent', '{CURTAIL_DURATION}' as 'duration', and the text '{REQUESTED_BY}' as 'requested_by'.
7. Limiting the power relieves the gearbox and does not repair it. Also recommend an inspection in the next low-wind period (procedure SOP-GBX-001).
8. WT-07 has a worn gearbox bearing and runs about 1 mm/s above the fleet. That is known and is not a new condition unless it crosses a threshold above.
"""


def setup_text() -> str:
    return "*** Business Goals ***\n" + goals() + "\n\n" + instructions()


# The action takes no 'command': the notebook's own value is curtail, so this action can limit a turbine
# and cannot stop one, whatever is typed into its parameters.
PARAMETERS = [
    ("turbine", "The turbine to limit, as in the column TurbineId, for example WT-03. One turbine, never empty."),
    ("percent", f"The power limit in percent of rated power, as in the column CurtailToPercent. Normally {CURTAIL_PERCENT}. A number from 0 to 100."),
    ("duration", f"How long the limit lasts before it ends by itself, for example {CURTAIL_DURATION}. A number and s, m or h."),
    ("requested_by", f"Who asks for it. Always the text: {REQUESTED_BY}"),
]


def action_description() -> str:
    f = facts()
    return ("Limits the power of one wind turbine to a percentage of its rated power for a limited time, by sending a "
            "curtail command to the edge of the wind farm. Use it for a running turbine whose gearbox shows the early "
            f"warning. The limit ends by itself after the duration. At {CURTAIL_PERCENT} percent a turbine delivers at most "
            f"{f['limitKw']:.0f} kW.")


def _wrap(text: str, width: int, indent: str) -> str:
    lines, line = [], ""
    for word in text.split():
        if line and len(line) + 1 + len(word) > width:
            lines.append(line)
            line = word
        else:
            line = f"{line} {word}".strip()
    return ("\n" + indent).join(lines + [line])


