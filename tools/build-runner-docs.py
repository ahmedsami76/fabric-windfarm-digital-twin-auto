#!/usr/bin/env python3
"""Writes the table of steps in docs/15-deployment-runner.md from the runner's own catalogue.

    python3 tools/build-runner-docs.py           write the table between the two markers
    python3 tools/build-runner-docs.py --check   fail when the document's table is not what the catalogue says
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
from deployer.core import Options  # noqa: E402
from deployer.steps_later import catalogue  # noqa: E402

DOC = ROOT / "docs" / "15-deployment-runner.md"
BEGIN, END = "<!-- steps: generated by tools/build-runner-docs.py -->", "<!-- end of steps -->"
DEFAULT = {"optin:pip-jobs"}       # what tools/deploy.py grants unless --no-pip-jobs is given
EVERYTHING = DEFAULT | {"roles", "preview:data-agent-sdk", "preview:ontology", "preview:operations-agent"}
HEADINGS = {"preflight": "Before anything is created", "phase1": "Phase 1", "phase2": "Phase 2", "phase3": "Phase 3",
            "phase4": "Phase 4", "phase5a": "Phase 5a, only with `--enable-phase5a-isolated-simulator` or `--enable-phase5-isolated-simulator`",
            "phase5bc": "Phases 5b and 5c, only with `--enable-phase5-isolated-simulator`"}


def who(step, bare, plain) -> str:
    """step: with everything allowed. plain: as the runner is started without options. bare: with --no-pip-jobs."""
    if step.optional:           # an optional step is never run by the runner, whatever was allowed
        return "you, optional"
    if plain is None:           # a step that only exists once its preview is allowed
        return "the runner, only with `--allow-preview operations-agent`"
    if plain.act is None and step.act is not None:
        need = next(f"`--allow-preview {n.split(':', 1)[1]}`" for n in sorted(EVERYTHING - DEFAULT)
                    if catalogue_has_act(step.id, DEFAULT | {n}))
        return f"you{', optional' if plain.optional else ''}; the runner with {need}"
    if plain.act is not None and bare.act is None:
        return "the runner; you with `--no-pip-jobs`"
    if plain.act is None:
        if plain.id.startswith("pre.") or plain.prerequisite and "tenant_settings" not in plain.id and plain.id != "p5a.isolation":
            return "check"
        if "gate" in plain.id:
            return "gate"
        return "you" if step.title == plain.title else "you; less of it with `--allow-preview operations-agent`"
    if "roles" in plain.needs:
        return "the runner, after `--approve-role-changes`"
    if "capacity" in plain.needs:
        return "the runner, only when you chose a new capacity, after `--approve-capacity-creation`"
    return "gate" if "gate" in plain.id else "the runner"


def steps_with(granted) -> dict:
    return {step.id: step for step in catalogue(Options(up_to="phase4", phase5a=True, phase5bc=True, granted=set(granted)))}


def catalogue_has_act(step_id: str, granted) -> bool:
    return steps_with(granted)[step_id].act is not None


def table() -> str:
    bare, plain, eager = steps_with(set()), steps_with(DEFAULT), steps_with(EVERYTHING)
    rows, phase = [], None
    for step in eager.values():
        if step.phase != phase:
            phase = step.phase
            rows += ["", f"**{HEADINGS[phase]}**", "", "| Step | What | Who | Changes | Rests on |", "|---|---|---|---|---|"]
        shown = plain.get(step.id, step)
        rows.append(f"| `{step.id}` | {shown.title} | {who(step, bare.get(step.id), plain.get(step.id))} "
                    f"| {step.writes or 'nothing'} | {step.basis if step.act else shown.basis} |")
    return "\n".join(rows).strip()


def main(argv) -> int:
    text = DOC.read_text(encoding="utf-8")
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    wanted = f"{head}{BEGIN}\n\n{table()}\n\n{END}{tail}"
    if "--check" in argv:
        if wanted != text:
            print("docs/15-deployment-runner.md: the table of steps is not what the catalogue says. Run tools/build-runner-docs.py.")
            return 1
        print("the runner's document is up to date")
        return 0
    DOC.write_text(wanted, encoding="utf-8")
    print(f"wrote the table of steps into {DOC.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
