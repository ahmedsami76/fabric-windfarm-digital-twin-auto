#!/usr/bin/env python3
"""Writes the table of steps in docs/15-deployment-runner.md from the runner's own catalogue.

    python3 tools/build-runner-docs.py           write the table between the two markers
    python3 tools/build-runner-docs.py --check   fail when the document's table is not what the catalogue says
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
from deployer.core import Options  # noqa: E402
from deployer.steps_later import catalogue  # noqa: E402

DOC = ROOT / "docs" / "15-deployment-runner.md"
BEGIN, END = "<!-- steps: generated by tools/build-runner-docs.py -->", "<!-- end of steps -->"
EVERYTHING = {"roles", "preview:data-agent-sdk", "preview:ontology", "optin:pip-jobs"}
HEADINGS = {"preflight": "Before anything is created", "phase1": "Phase 1", "phase2": "Phase 2", "phase3": "Phase 3",
            "phase4": "Phase 4", "phase5a": "Phase 5a, only with `--enable-phase5a-isolated-simulator`"}


def who(plain, eager) -> str:
    if eager.optional:          # an optional step is never run by the runner, whatever was allowed
        return "you, optional"
    if plain.act is None and eager.act is not None:
        need = "`--allow-preview ontology`" if "ontology" in plain.id else "`--opt-in pip-jobs`"
        if "preview:data-agent-sdk" in eager.needs:
            need += " and `--allow-preview data-agent-sdk`"
        return f"you{', optional' if plain.optional else ''}; the runner with {need}"
    if plain.act is None:
        if plain.id.startswith("pre.") or plain.prerequisite and "tenant_settings" not in plain.id and plain.id != "p5a.isolation":
            return "check"
        if "gate" in plain.id:
            return "gate"
        return "you"
    if "roles" in plain.needs:
        return "the runner, after `--approve-role-changes`"
    return "gate" if "gate" in plain.id else "the runner"


def table() -> str:
    plain = catalogue(Options(up_to="phase4", phase5a=True))
    eager = {step.id: step for step in catalogue(Options(up_to="phase4", phase5a=True, granted=set(EVERYTHING)))}
    rows, phase = [], None
    for step in plain:
        if step.phase != phase:
            phase = step.phase
            rows += ["", f"**{HEADINGS[phase]}**", "", "| Step | What | Who | Changes | Rests on |", "|---|---|---|---|---|"]
        rows.append(f"| `{step.id}` | {step.title} | {who(step, eager[step.id])} | {step.writes or 'nothing'} | {step.basis} |")
    return "\n".join(rows).strip()


def main(argv) -> int:
    text = DOC.read_text(encoding="utf-8")
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    wanted = f"{head}{BEGIN}\n\n{table()}\n\n{END}{tail}"
    if "--check" in argv:
        if wanted != text:
            print("docs/15-deployment-runner.md: the table of steps is not what the catalogue says. Run tools/build-runner-docs.py.")
            return 1
        print("the runner's document is up to date")
        return 0
    DOC.write_text(wanted, encoding="utf-8")
    print(f"wrote the table of steps into {DOC.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
